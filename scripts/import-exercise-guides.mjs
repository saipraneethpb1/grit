// Usage: node scripts/import-exercise-guides.mjs /path/to/free-exercise-db/dist/exercises.json
// Imports guidance only; never changes curated exercise IDs or training targets.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const curated = JSON.parse(readFileSync(new URL('data/exercises.curated.json', root))).exercises;
const source = new Map(JSON.parse(readFileSync(process.argv[2])).map(ex => [ex.id, ex]));
const guides = {};
const jobs = [];
for (const exercise of curated) {
  const original = source.get(exercise.source_id);
  if (!original?.instructions?.length || original.images?.length !== 2) {
    throw new Error(`Missing guidance: ${exercise.name}`);
  }
  const instructions = original.instructions.filter(step => typeof step === 'string').map(step => step.trim()).filter(Boolean);
  if (!instructions.length) throw new Error(`Empty instructions: ${exercise.name}`);
  guides[exercise.id] = { sourceId: original.id, instructions };
  original.images.forEach((path, index) => {
    if (!/^[a-zA-Z0-9_()'. -]+\/[01]\.jpg$/.test(path)) throw new Error(`Unexpected image path: ${path}`);
    jobs.push({ url: 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/' + path.split('/').map(encodeURIComponent).join('/'), name: `${exercise.id}-${index}.jpg` });
  });
}
mkdirSync(new URL('assets/exercises/', root), { recursive: true });
let next = 0;
await Promise.all(Array.from({ length: 8 }, async () => {
  while (next < jobs.length) {
    const job = jobs[next++];
    const destination = new URL('assets/exercises/' + job.name, root);
    if (existsSync(destination)) continue;
    const response = await fetch(job.url);
    if (!response.ok) throw new Error(`Download failed (${response.status}): ${job.name}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (bytes[0] !== 0xff || bytes[1] !== 0xd8) throw new Error('Expected JPEG');
    writeFileSync(destination, bytes);
  }
}));
writeFileSync(new URL('data/exercise-guides.json', root), JSON.stringify(guides, null, 2) + '\n');
const entries = curated.map(ex => `  '${ex.id}': [require('../../assets/exercises/${ex.id}-0.jpg'), require('../../assets/exercises/${ex.id}-1.jpg')],`).join('\n');
writeFileSync(new URL('src/domain/exerciseGuideImages.ts', root), `// Generated by scripts/import-exercise-guides.mjs; literal requires let Metro bundle offline assets.\nimport type { ImageSourcePropType } from 'react-native';\nexport const exerciseGuideImages: Record<string, [ImageSourcePropType, ImageSourcePropType]> = {\n${entries}\n};\n`);
console.log(`Imported ${curated.length} guides and ${jobs.length} demonstration images.`);
