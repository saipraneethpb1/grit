// Import rendered artwork without altering poses; encode WebP sheets for the offline app.
// Encoding uses the libvips CLI (`vips`), which writes WebP; Jimp only checks dimensions.
// Usage: node scripts/prepare-anatomical-demos.mjs --import <exercise-id> <image-path>
// After visual inspection: node scripts/prepare-anatomical-demos.mjs --reviewed <exercise-id>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
const require = createRequire(import.meta.url);
const Jimp = require('jimp-compact');
const root = fileURLToPath(new URL('../', import.meta.url));
const atlasPath = path.join(root, 'data/exercise-anatomy.json');
const atlas = JSON.parse(fs.readFileSync(atlasPath, 'utf8'));
const [operation, id, input] = process.argv.slice(2);
if (operation && !['--import', '--reviewed', '--batch'].includes(operation)) throw Error('Unknown operation');
if (operation && operation !== '--batch' && !atlas[id]) throw Error('Unknown exercise');
const assetDir = path.join(root, 'assets/anatomy');
fs.mkdirSync(assetDir, { recursive: true });
const jobs = operation === '--batch' ? JSON.parse(fs.readFileSync(id, 'utf8'))
  : operation === '--import' ? [{ id, path: input }] : [];
for (const job of jobs) {
  if (!atlas[job.id]) throw Error('Unknown exercise');
  const image = await Jimp.read(job.path);
  if (image.bitmap.width !== image.bitmap.height || image.bitmap.width % 2) {
    throw Error(`${job.id}: expected an even square 2×2 sheet, got ${image.bitmap.width}×${image.bitmap.height}`);
  }
}
/** Same pixels at q70 look identical at phone scale and are about a third of a q90 JPEG. */
function encode(input, output, quality, size) {
  const quiet = { stdio: ['ignore', 'ignore', 'inherit'], env: { ...process.env, VIPS_WARNING: '0' } };
  const source = size ? output + '.tmp.v' : input;
  if (size) execFileSync('vips', ['thumbnail', input, source, String(size), '--height', String(size)], quiet);
  execFileSync('vips', ['webpsave', source, output, '--Q', String(quality), '--smart-subsample', '--effort', '6', '--strip'], quiet);
  if (size) fs.rmSync(source);
}
// Validate the entire batch before replacing any existing artwork.
for (const job of jobs) {
  encode(job.path, path.join(assetDir, `${job.id}.webp`), 70);
  encode(job.path, path.join(assetDir, `${job.id}-thumb.webp`), 75, 256);
  atlas[job.id].status = job.reviewed ? 'reviewed' : 'generated';
  atlas[job.id].artwork = path.basename(job.path);
}
if (operation === '--reviewed') {
  if (!fs.existsSync(path.join(assetDir, `${id}.webp`))) throw Error('No artwork to review');
  atlas[id].status = 'reviewed';
}
fs.writeFileSync(atlasPath, JSON.stringify(atlas, null, 2) + '\n');
const reviewed = Object.keys(atlas).filter(id => atlas[id].status === 'reviewed');
const entries = reviewed.map(id => `  '${id}': require('../../assets/anatomy/${id}.webp'),`);
const thumbnails = reviewed.map(id => `  '${id}': require('../../assets/anatomy/${id}-thumb.webp'),`);
fs.writeFileSync(path.join(root, 'src/domain/exerciseAnatomyAssets.ts'),
  `// Generated by scripts/prepare-anatomical-demos.mjs; literal requires bundle offline artwork.\nimport type { ImageSourcePropType } from 'react-native';\n\nexport const exerciseAnatomyAssets: Record<string, ImageSourcePropType> = {\n${entries.join('\n')}\n};\n\nexport const exerciseAnatomyThumbnails: Record<string, ImageSourcePropType> = {\n${thumbnails.join('\n')}\n};\n`);
console.log(`${reviewed.length}/${Object.keys(atlas).length} anatomical demonstrations reviewed.`);
